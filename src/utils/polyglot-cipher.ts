// Pre-computed once at module load — shared across all calls.
const POOL: string[] = POOL_CODEPOINTS.map((cp) => String.fromCodePoint(cp));
const POOL_SIZE = POOL.length;
const INDEX_MAP = new Map<string, number>(POOL.map((c, i) => [c, i]));

// ---------------------------------------------------------------------------
// Key derivation
// ---------------------------------------------------------------------------

function deriveSubKeys(key: string, count: number): number[] {
  const primes = [31, 37, 41, 43, 47, 53, 59, 61, 67, 71];
  const result: number[] = [];
  for (let i = 0; i < count; i++) {
    let h1 = (0xdeadbeef ^ (i * 0x12345678)) >>> 0;
    let h2 = (0x41c6ce57 ^ (i * 0x87654321)) >>> 0;
    for (let j = 0; j < key.length; j++) {
      const ch = key.charCodeAt(j);
      h1 = Math.imul(h1 ^ ch, primes[j % primes.length] * (i + 1));
      h2 = Math.imul(h2 ^ ch, primes[(j + i) % primes.length]);
      h1 ^= h2 >>> 17;
      h2 ^= h1 >>> 13;
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
    h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
    h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    result.push((h1 ^ h2) >>> 0);
  }
  return result;
}

// ---------------------------------------------------------------------------
// Mulberry32 PRNG
// ---------------------------------------------------------------------------

function createPRNG(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---------------------------------------------------------------------------
// Layers
// ---------------------------------------------------------------------------

function generatePermutation(seed: number): number[] {
  const perm = Array.from({ length: POOL_SIZE }, (_, i) => i);
  const rng = createPRNG(seed);
  for (let i = POOL_SIZE - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [perm[i], perm[j]] = [perm[j], perm[i]];
  }
  return perm;
}

function invertPermutation(perm: number[]): number[] {
  const inv = new Array<number>(perm.length);
  for (let i = 0; i < perm.length; i++) inv[perm[i]] = i;
  return inv;
}

function applySubstitution(text: string, seed: number, mode: 'encode' | 'decode'): string {
  const perm = generatePermutation(seed);
  const mapping = mode === 'encode' ? perm : invertPermutation(perm);
  return [...text]
    .map((char) => {
      const idx = INDEX_MAP.get(char);
      return idx === undefined ? char : POOL[mapping[idx]];
    })
    .join('');
}

function applyPositionalShift(text: string, seed: number, mode: 'encode' | 'decode'): string {
  const rng = createPRNG(seed);
  return [...text]
    .map((char) => {
      // Check letter first — non-letters pass through WITHOUT advancing the PRNG.
      // This ensures markdown syntax chars (# | > * etc.) that are stripped by the
      // HTML renderer do NOT corrupt the cipher-stream position when decoding DOM text.
      const idx = INDEX_MAP.get(char);
      if (idx === undefined) return char;
      const shift = Math.floor(rng() * POOL_SIZE); // advance PRNG only for letters
      if (mode === 'encode') return POOL[(idx + shift) % POOL_SIZE];
      return POOL[((idx - shift) % POOL_SIZE + POOL_SIZE) % POOL_SIZE];
    })
    .join('');
}

function applyFeedbackShift(text: string, seed: number, mode: 'encode' | 'decode'): string {
  const rng = createPRNG(seed);
  let prev = seed % POOL_SIZE;
  const result: string[] = [];

  for (const char of [...text]) {
    const idx = INDEX_MAP.get(char);

    if (idx === undefined) {
      // Non-letter: pass through WITHOUT advancing PRNG or updating feedback state.
      result.push(char);
      continue;
    }

    const baseShift = Math.floor(rng() * POOL_SIZE); // advance only for letters

    const totalShift = (baseShift + prev) % POOL_SIZE;

    if (mode === 'encode') {
      const newIdx = (idx + totalShift) % POOL_SIZE;
      result.push(POOL[newIdx]);
      prev = newIdx;
    } else {
      const originalIdx = ((idx - totalShift) % POOL_SIZE + POOL_SIZE) % POOL_SIZE;
      result.push(POOL[originalIdx]);
      prev = idx;
    }
  }

  return result.join('');
}

